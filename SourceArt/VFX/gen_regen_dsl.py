# Generates Saved/regen_dsl/RegenFXOn.dsl + RegenFXOff.dsl (hero BP_ThirdPersonCharacter).
# REGEN LOOK v2 (user 2026-10-23 Regen concept: green / gold light ribbons coiling around his arms, legs and torso).
# v1 painted bands on his skin (M_RegenSpiral overlay) and read as patchy green; v2 attaches a real glowing coil
# (SM_RegenCoil: helix ribbon, radius 100 / height 100 along +Z, M_RegenRibbon pulses racing along it) to each limb bone.
# Bone axes (PIE probe 2026-10-23, child offset in parent bone space): every limb bone runs along its local X; left arm
# / right leg +X, right arm / left leg -X. The coil's +Z is turned onto the bone's +X with Pitch -90 (or -X with +90).
OUT = r"C:/repos/Unreal Projects/Timeshift3D/Saved/regen_dsl/"
COILS = [  # bone, sign of the bone axis, length (cm), coil radius (cm)
    ("upperarm_l", 1, 27.8, 9.0), ("upperarm_r", -1, 27.8, 9.0),
    ("lowerarm_l", 1, 27.3, 8.0), ("lowerarm_r", -1, 27.3, 8.0),
    ("thigh_l", -1, 43.3, 12.0), ("thigh_r", 1, 43.3, 12.0),
    ("calf_l", -1, 42.2, 10.0), ("calf_r", 1, 42.2, 10.0),
    ("spine_02", 1, 45.0, 21.0)]

def coil(i, bone, sign, length, radius, inner):
    pitch = -90.0 if sign > 0 else 90.0
    s = radius / 100.0
    return """(bind c%(i)d (Utilities|Casting|CastToStaticMeshComponent :Object (Game|AddComponentbyClass self "/Script/Engine.StaticMeshComponent"))
  (:then
    (Components|StaticMesh|SetStaticMesh :self c%(i)d :NewMesh "/Game/Timeshift/VFX/Regen/SM_RegenCoil.SM_RegenCoil")
    (Collision|SetCollisionEnabled :self c%(i)d :NewType "NoCollision")
    (Rendering|SetCastShadow :self c%(i)d :NewCastShadow false)
    (Transformation|AttachComponentToComponent :self c%(i)d :Parent mesh :SocketName "%(bone)s" :LocationRule "SnapToTarget" :RotationRule "SnapToTarget" :ScaleRule "KeepRelative" :bWeldSimulatedBodies false)
    (Transformation|SetRelativeRotation :self c%(i)d :NewRotation "(Pitch=%(pitch).6f,Yaw=%(yaw).6f,Roll=0.000000)" :bSweep false :bTeleport true)
    (Transformation|SetRelativeScale3D c%(i)d (Math|Vector|MakeVector %(s).3f %(s).3f %(l).3f))
    (Utilities|Array|Add :TargetArray (Variables|Default|GetRegenCoils) :NewItem c%(i)d)
%(inner)s)
  (:CastFailed))""" % dict(i=i, bone=bone, pitch=pitch, yaw=0.0, s=s, l=length / 100.0, inner=inner)

inner = ""
for i, (bone, sign, length, radius) in reversed(list(enumerate(COILS))):
    body = coil(i, bone, sign, length, radius, inner)
    inner = "\n".join("    " + ln for ln in body.split("\n"))
on = """(fn RegenFXOn ()
  ; REGEN LOOK v2 (user 2026-10-23 Regen concept: green / gold light ribbons coiling around his arms, legs and torso):
  ; a glowing SM_RegenCoil (M_RegenRibbon - green-gold light pulses racing along a helix ribbon) attached to each upper
  ; arm, forearm, thigh, shin and the torso + NS_RegenMotes (green-gold motes rising off him). Generated by
  ; C:/agentpy/gen_regen_dsl.py (bone axes / lengths from a PIE probe). v1 surface-band overlay M_RegenSpiral is unused.
  (bind mesh (Variables|Character|GetMesh))
  (if (== (Utilities|Array|Length (Variables|Default|GetRegenCoils)) 0)
%s)
  ; (the IsValid macro branches, so it has to be the last statement)
  (Utilities|IsValid (Variables|Default|GetRegenFX)
    (:"Is Not Valid"
      (Variables|Default|SetRegenFX (Niagara|SpawnSystemAttached :SystemTemplate "/Game/Timeshift/VFX/Regen/NS_RegenMotes.NS_RegenMotes" :AttachToComponent mesh :AttachPointName "root" :Location (Math|Vector|MakeVector 0.0 0.0 0.0) :LocationType "SnapToTarget" :bAutoDestroy false)))))
""" % inner
off = """(fn RegenFXOff ()
  ; undo RegenFXOn: remove the coils and the motes
  (for c (Variables|Default|GetRegenCoils)
    (Components|DestroyComponent :self c))
  (Utilities|Array|Clear :TargetArray (Variables|Default|GetRegenCoils))
  (Utilities|IsValid (Variables|Default|GetRegenFX)
    (:"Is Valid"
      (Components|DestroyComponent :self (Variables|Default|GetRegenFX)))))
"""
open(OUT + "RegenFXOn.dsl", "w").write(on)
open(OUT + "RegenFXOff.dsl", "w").write(off)
print("ok", on.count("CastToStaticMeshComponent"))
